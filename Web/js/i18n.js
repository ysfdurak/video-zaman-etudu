/** Masaüstü sürümü bu sözlükten metin dosyası üretir (Tools/Metinler/uret.mjs). */
export { DICT, RESULTS };

export const LANGS = ["tr", "en"];
const STORAGE_KEY = "vze.lang";

function storedLang() {
  try { return localStorage.getItem(STORAGE_KEY); } catch { return null; }
}

function detect() {
  const param = new URLSearchParams(globalThis.location?.search ?? "").get("lang");
  if (LANGS.includes(param)) return param;
  const stored = storedLang();
  if (LANGS.includes(stored)) return stored;
  const prefs = globalThis.navigator?.languages ?? [globalThis.navigator?.language ?? "tr"];
  return prefs.some((l) => String(l).toLowerCase().startsWith("tr")) ? "tr" : "en";
}

let current = detect();

export const getLang = () => current;
export const locale = () => (current === "tr" ? "tr-TR" : "en-US");

export function setLang(lang) {
  if (!LANGS.includes(lang)) return;
  current = lang;
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* gizli pencere vb. */ }
}

/** Anahtarı geçerli dile çevirir; {ad} yer tutucularını doldurur. */
export function t(key, params = {}, lang = current) {
  const text = DICT[lang]?.[key] ?? DICT.tr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** core.js sonuç metnini (ör. "Yeterli") geçerli dile çevirir. */
export const result = (value, lang = current) => (value && RESULTS[value] ? RESULTS[value][lang] : value);

/** Sözlükteki anahtar kümeleri iki dilde aynı mı? (test için) */
export const missingKeys = () => {
  const tr = Object.keys(DICT.tr), en = Object.keys(DICT.en);
  return { onlyTr: tr.filter((k) => !(k in DICT.en)), onlyEn: en.filter((k) => !(k in DICT.tr)) };
};

/**
 * Sayfadaki sabit metinler: data-i18n (metin), data-i18n-html (güvenilir sözlük HTML'i),
 * data-i18n-attr="title:anahtar;aria-label:anahtar".
 */
export function applyStatic(root = document) {
  document.documentElement.lang = current;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll("[data-i18n-attr]"))
    for (const pair of el.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":");
      el.setAttribute(attr, t(key));
    }
}
